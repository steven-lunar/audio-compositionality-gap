"""
Compositional (select-then-answer) evaluation on the EMOTION-CUE dataset
(output of emotion_builder.py). Direct structural analog of gender_eval.py,
with the selection cue changed from speaker gender to speaker emotion: "the
question asked by the angry/happy/sad/... -sounding speaker". Audio is
clean TTS concatenation (no noise mixing), so the prompt does not mention
background sounds.

CUE IS EMOTION ONLY, NOT GENDER+EMOTION -- even though emotion_builder.py's
records also carry target_gender/distractor_gender (gender is guaranteed to
differ between target and distractor too, per that script's requirement),
the PROMPT here only ever names the target's emotion, never its gender.
This keeps the emotion-cue experiment a clean, single-axis addition to the
existing cue-type comparison (background-noise cue vs. gender cue vs.
emotion cue), rather than a compound gender+emotion cue task -- exactly
mirroring how gender_eval.py's prompt never mentioned bg_category even
though that field was also present in its metadata. Gender is still read
and tracked in the output/summary (see EXTRA CONDITIONING AXES below) purely
as a secondary analysis dimension, never as part of what the model is told.

Works for both tasks generated by emotion_builder.py:
  task="math"   -> extract_math_answer, exact match
  task="trivia" -> extract_trivia_answer, normalize_answer set membership

Conventions kept from gender_eval.py:
  * target read from the pre-assigned record["target_index"] (falls back to
    random.Random(concat_id).choice for any metadata that somehow lacks it,
    same defensive fallback gender_eval.py has -- in practice
    emotion_builder.py always writes target_index)
  * checkpoint/resume on concat_id, JSONL append
  * error_type in {Correct, Distracted, Hallucination}
  * thin per-task/per-style wrappers delegating to one shared implementation

EXTRA CONDITIONING AXES (generalizing gender_eval's target_gender/
target_index split): this dataset has THREE attributes worth conditioning
accuracy on, not two --
  * target_index   (positional bias: 1st segment vs. 2nd segment)
  * target_emotion (the actual cue -- 5 values, not 2)
  * target_gender  (NOT the cue, but still fully controlled/balanced by
    emotion_builder.py against the emotion cue, so "does accuracy differ by
    the target's gender even though gender was never mentioned" is a
    legitimate free secondary check, analogous to grader.py's "always
    report the axis you have data for, don't just discard it" habit)
The summary prints P(correct | ...) for all three axes. is_distracted /
all_distractors_info are also enriched with both matched_distractor_emotion
AND matched_distractor_gender (gender_eval.py only had matched_distractor_
gender, since gender was its only non-target attribute; here there's an
extra one).
"""

import json
import os
import random

from tqdm import tqdm
from src.evaluators.extractor import *

import string
from whisper.normalizers import EnglishTextNormalizer

whisper_normalizer = EnglishTextNormalizer()

def normalize_answer(s):
    """Lower text and remove punctuation, articles and extra whitespace."""
    s = whisper_normalizer(s)
    def remove_articles(text):
        return re.sub(r'\b(a|an|the)\b', ' ', text)

    def white_space_fix(text):
        return ' '.join(text.split())

    def handle_punc(text):
        exclude = set(string.punctuation + "".join([u"‘", u"’", u"´", u"`"]))
        return ''.join(ch if ch not in exclude else ' ' for ch in text)

    def lower(text):
        return text.lower()

    def replace_underscore(text):
        return text.replace('_', ' ')

    return white_space_fix(remove_articles(handle_punc(lower(replace_underscore(s))))).strip()

# Adjective used to describe "the speaker who sounds ___" in the prompt.
# ADJUST IF NEEDED: pick whichever wording best matches how your emo_ref_audio
# reference clips were actually performed/labeled (e.g. "fearful" vs "scared"
# vs "afraid" for the "fear" category).
EMOTION_ADJ = {
    "angry": "angry",
    "disgust": "disgusted",
    "fear": "fearful",
    "happy": "happy",
    "sad": "sad",
}


def get_expected_answers(segment):
    """Normalize the two metadata schemas to a list of answer strings:
      trivia: "expected_answers" -> list of strings
      math:   "expected_answer"  -> single number stored as a string
    """
    if "expected_answers" in segment:
        answers = segment["expected_answers"]
        return [str(a) for a in answers] if isinstance(answers, list) \
            else [str(answers)]
    if "expected_answer" in segment:
        return [str(segment["expected_answer"])]
    raise KeyError(
        "Segment has neither 'expected_answers' nor 'expected_answer': "
        f"{list(segment.keys())}"
    )


def build_emotion_prompt(task, target_emotion):
    adj = EMOTION_ADJ[target_emotion]
    if task == "math":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "math problems played sequentially, each spoken with a different "
            "emotional tone of voice.\n"
            f"Find the math problem spoken by the {adj}-sounding speaker and "
            "calculate its answer.\n"
            "Output ONLY the final number inside <ans> and </ans> tags. "
            "Do not output any reasoning, equations, or other text."
        )
    if task == "trivia":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "trivia questions played sequentially, each spoken with a "
            "different emotional tone of voice.\n"
            f"Find the trivia question spoken by the {adj}-sounding speaker "
            "and answer it.\n"
            "CRITICAL INSTRUCTION: Provide the absolute shortest possible "
            "answer. Output ONLY the core entity, name, or word.\n"
            "Output the concise answer inside <ans> and </ans> tags. "
            "Do not output any reasoning or other text."
        )
    raise ValueError(f"Unknown task: {task}")


def build_emotion_cot_prompt(task, target_emotion):
    """CoT variant, mirroring gender_eval.py's CoT prompt structure: numbered
    steps, then the tag contract with the explicit 'no reasoning inside the
    tag' clause."""
    adj = EMOTION_ADJ[target_emotion]
    if task == "math":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "math problems played sequentially, each spoken with a different "
            "emotional tone of voice.\n"
            "Think through this step by step:\n"
            f"1. Identify which segment is spoken by the {adj}-sounding speaker.\n"
            "2. State the math problem spoken in that segment.\n"
            "3. Compute the answer to that math problem.\n"
            "After your reasoning, output ONLY the final number inside <ans> "
            "and </ans> tags.\n"
            "The <ans> tag must contain only the final numeric answer -- no "
            "reasoning inside the tag itself."
        )
    if task == "trivia":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "trivia questions played sequentially, each spoken with a "
            "different emotional tone of voice.\n"
            "Think through this step by step:\n"
            f"1. Identify which segment is spoken by the {adj}-sounding speaker.\n"
            "2. State the trivia question spoken in that segment.\n"
            "3. Answer that trivia question.\n"
            "After your reasoning, output ONLY the shortest possible answer "
            "(the core entity, name, or word) inside <ans> and </ans> tags.\n"
            "The <ans> tag must contain only the concise final answer -- no "
            "reasoning inside the tag itself."
        )
    raise ValueError(f"Unknown task: {task}")


def _pre_tag_text_len(raw):
    """Length of text preceding the first <ans> tag -- a cheap indicator of
    whether the model produced visible reasoning under CoT."""
    idx = raw.lower().find("<ans>")
    return len(raw[:idx].strip()) if idx >= 0 else len(raw.strip())


def _grade(task, prediction_raw, expected_answers):
    """Returns (prediction_clean, is_correct)."""
    if task == "math":
        prediction_clean = extract_math_answer(prediction_raw)
        is_correct = any(prediction_clean == str(a) for a in expected_answers)
    else:  # trivia
        extracted = extract_trivia_answer(prediction_raw)
        prediction_clean = normalize_answer(extracted)
        gt_norm = [normalize_answer(str(a)) for a in expected_answers]
        is_correct = prediction_clean in gt_norm if prediction_clean else False
    return prediction_clean, is_correct


def _matches_answers(task, prediction_clean, expected_answers):
    if not prediction_clean:
        return False
    if task == "math":
        return any(prediction_clean == str(a) for a in expected_answers)
    return prediction_clean in [normalize_answer(str(a)) for a in expected_answers]


def evaluate_conditional_emotion(model, dataset_dir, metadata_path, output_path,
                                  task="math", use_cot=False):
    assert task in ("math", "trivia")
    style = "CoT" if use_cot else "baseline"
    print(f"\n--- Starting Emotion-Conditioned Compositional Evaluation "
          f"({task}, {style}) ---")

    with open(metadata_path, "r", encoding="utf-8") as f:
        records = [json.loads(line.strip()) for line in f]

    # ==========================================
    # Checkpoint and resume logic
    # ==========================================
    processed_ids = set()
    correct_count = 0
    total_tested = 0
    # accuracy conditioned on target position, target emotion (the cue),
    # AND target gender (not the cue, but fully controlled -- see module
    # docstring's EXTRA CONDITIONING AXES note).
    cond = {("pos", 0): [0, 0], ("pos", 1): [0, 0]}
    for emo in EMOTION_ADJ:
        cond[("emo", emo)] = [0, 0]
    for gen in ("male", "female"):
        cond[("gen", gen)] = [0, 0]

    def _tally(data):
        nonlocal correct_count, total_tested
        total_tested += 1
        ok = bool(data.get("is_correct"))
        if ok:
            correct_count += 1
        p = data.get("target_index")
        e = data.get("target_emotion")
        g = data.get("target_gender")
        if ("pos", p) in cond:
            cond[("pos", p)][0] += ok
            cond[("pos", p)][1] += 1
        if ("emo", e) in cond:
            cond[("emo", e)][0] += ok
            cond[("emo", e)][1] += 1
        if ("gen", g) in cond:
            cond[("gen", g)][0] += ok
            cond[("gen", g)][1] += 1

    if os.path.exists(output_path):
        with open(output_path, "r", encoding="utf-8") as f:
            for line in f:
                try:
                    data = json.loads(line.strip())
                    processed_ids.add(data["concat_id"])
                    _tally(data)
                except json.JSONDecodeError:
                    continue

    if processed_ids:
        print(f"Detected historical progress! {len(processed_ids)} tests completed.")
        print(
            f"Current historical accuracy: "
            f"{correct_count / total_tested:.2%} ({correct_count}/{total_tested})"
        )
        print("Automatically skipping completed items...\n")
    # ==========================================

    for record in tqdm(records, desc=f"Emotion-Conditioned {task}"):
        concat_id = record["concat_id"]
        if concat_id in processed_ids:
            continue

        audio_path = os.path.join(dataset_dir, record["audio_path"])

        # Prefer the pre-assigned balanced target from the dataset metadata
        # (emotion_builder.py always writes this). Fall back to the
        # seeded-random convention for any metadata without the field,
        # same defensive pattern as gender_eval.py.
        if "target_index" in record:
            target_index = record["target_index"]
            target_segment = record["sequence"][target_index]
        else:
            rng = random.Random(concat_id)
            target_segment = rng.choice(record["sequence"])
            target_index = record["sequence"].index(target_segment)
        target_gender = target_segment["gender"]
        target_emotion = target_segment["emotion"]
        expected_answers = get_expected_answers(target_segment)
        distractors = [
            seg for i, seg in enumerate(record["sequence"]) if i != target_index
        ]

        if use_cot:
            prompt = build_emotion_cot_prompt(task, target_emotion)
        else:
            prompt = build_emotion_prompt(task, target_emotion)

        prediction_raw = model.query(audio_path, prompt).strip()
        prediction_clean, is_correct = _grade(task, prediction_raw, expected_answers)

        # Distractor match
        is_distracted = False
        matched_distractor_emotion = None
        matched_distractor_gender = None
        if not is_correct:
            for dist in distractors:
                if _matches_answers(task, prediction_clean,
                                    get_expected_answers(dist)):
                    is_distracted = True
                    matched_distractor_emotion = dist["emotion"]
                    matched_distractor_gender = dist["gender"]
                    break

        if is_correct:
            error_type = "Correct"
        elif is_distracted:
            error_type = "Distracted"
        else:
            error_type = "Hallucination"

        result_dict = {
            "concat_id": concat_id,
            "task": task,
            "cue_type": "emotion",
            "prompt_style": "cot" if use_cot else "baseline",
            # visible-reasoning indicator (chars before the first <ans> tag);
            # only meaningful under CoT, recorded always for symmetry
            "pre_tag_text_len": _pre_tag_text_len(prediction_raw),
            "target_emotion": target_emotion,
            "target_gender": target_gender,
            "target_index": target_index,
            "target_question": target_segment["question"],
            "ground_truth": expected_answers,
            "prediction_raw": prediction_raw,
            "prediction_clean": prediction_clean,
            "is_correct": is_correct,
            "error_type": error_type,
            "is_distracted": is_distracted,
            "matched_distractor_emotion": matched_distractor_emotion,
            "matched_distractor_gender": matched_distractor_gender,
            "all_distractors_info": [
                {"emotion": d["emotion"],
                 "gender": d["gender"],
                 "expected_answers": get_expected_answers(d)}
                for d in distractors
            ],
        }

        _tally(result_dict)
        processed_ids.add(concat_id)

        with open(output_path, "a", encoding="utf-8") as out_f:
            out_f.write(json.dumps(result_dict, ensure_ascii=False) + "\n")

        display_gt = expected_answers[0] if expected_answers else ""
        print(
            f"\n[Concat ID: {concat_id} | Target: {target_emotion}/{target_gender} @ pos "
            f"{target_index}] GT: {display_gt} | Pred: {prediction_clean} | "
            f"Correct: {is_correct} | {error_type}"
        )

    # ---------------- Summary ----------------
    if not total_tested:
        print("No items evaluated.")
        return
    print(f"\nOverall accuracy: {correct_count / total_tested:.2%} "
          f"({correct_count}/{total_tested})")
    for (kind, key), (ok, n) in cond.items():
        if n:
            if kind == "pos":
                label = f"target={'1st' if key == 0 else '2nd'} segment"
            elif kind == "emo":
                label = f"target emotion={key}"
            else:
                label = f"target gender={key} (not the cue)"
            print(f"P(correct | {label}): {ok / n:.2%}  (n={n})")


# Thin per-task wrappers, matching the codebase convention of
# evaluate_conditional_gender_math / evaluate_conditional_gender_trivia.
# Single shared implementation above -> graders cannot drift apart.

def evaluate_conditional_emotion_math(model, dataset_dir, metadata_path,
                                       output_path):
    return evaluate_conditional_emotion(
        model, dataset_dir, metadata_path, output_path, task="math")


def evaluate_conditional_emotion_trivia(model, dataset_dir, metadata_path,
                                         output_path):
    return evaluate_conditional_emotion(
        model, dataset_dir, metadata_path, output_path, task="trivia")


def evaluate_conditional_emotion_math_cot(model, dataset_dir, metadata_path,
                                          output_path):
    return evaluate_conditional_emotion(
        model, dataset_dir, metadata_path, output_path, task="math",
        use_cot=True)


def evaluate_conditional_emotion_trivia_cot(model, dataset_dir, metadata_path,
                                            output_path):
    return evaluate_conditional_emotion(
        model, dataset_dir, metadata_path, output_path, task="trivia",
        use_cot=True)