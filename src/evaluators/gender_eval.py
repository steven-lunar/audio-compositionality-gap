"""
Compositional (select-then-answer) evaluation on the GENDER-CUE dataset.

Same design as the env-sound baseline, with the selection cue changed from a
background sound to speaker gender: "the question asked by the man/woman".
Audio is CLEAN concatenation (no noise mixing), so the prompt deliberately
does not mention background sounds.

Works for both tasks generated by generate_gender_dataset.py:
  task="math"   -> extract_math_answer, exact match
  task="trivia" -> extract_trivia_answer, normalize_answer set membership

Conventions kept from the baseline template:
  * target chosen via random.Random(concat_id).choice -> item-paired with
    other runs on the same metadata
  * checkpoint/resume on concat_id, JSONL append
  * error_type in {Correct, Distracted, Hallucination}
Extra fields for the cue-channel contrast analysis:
  * target_gender, target_index (positional-bias split)
Summary prints position- and gender-conditioned accuracy.
"""

import json
import os
import random

from tqdm import tqdm
from src.evaluators.extractor import *

import string
from whisper.normalizers import EnglishTextNormalizer

whisper_normalizer = EnglishTextNormalizer()

def normalize_answer(s):
    """Lower text and remove punctuation, articles and extra whitespace."""
    s = whisper_normalizer(s)
    def remove_articles(text):
        return re.sub(r'\b(a|an|the)\b', ' ', text)

    def white_space_fix(text):
        return ' '.join(text.split())

    def handle_punc(text):
        exclude = set(string.punctuation + "".join([u"‘", u"’", u"´", u"`"]))
        return ''.join(ch if ch not in exclude else ' ' for ch in text)

    def lower(text):
        return text.lower()

    def replace_underscore(text):
        return text.replace('_', ' ')

    return white_space_fix(remove_articles(handle_punc(lower(replace_underscore(s))))).strip()

GENDER_NOUN = {"male": "man", "female": "woman"}
 
 
def get_expected_answers(segment):
    """Normalize the two metadata schemas to a list of answer strings:
      trivia: "expected_answers" -> list of strings
      math:   "expected_answer"  -> single number stored as a string
    """
    if "expected_answers" in segment:
        answers = segment["expected_answers"]
        return [str(a) for a in answers] if isinstance(answers, list) \
            else [str(answers)]
    if "expected_answer" in segment:
        return [str(segment["expected_answer"])]
    raise KeyError(
        "Segment has neither 'expected_answers' nor 'expected_answer': "
        f"{list(segment.keys())}"
    )
 
 
def build_gender_prompt(task, target_gender):
    noun = GENDER_NOUN[target_gender]
    if task == "math":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "math problems played sequentially, one spoken by a male voice and "
            "one spoken by a female voice.\n"
            f"Find the math problem that is asked by the {noun} and calculate "
            "its answer.\n"
            "Output ONLY the final number inside <ans> and </ans> tags. "
            "Do not output any reasoning, equations, or other text."
        )
    if task == "trivia":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "trivia questions played sequentially, one spoken by a male voice "
            "and one spoken by a female voice.\n"
            f"Find the trivia question that is asked by the {noun} and answer it.\n"
            "CRITICAL INSTRUCTION: Provide the absolute shortest possible "
            "answer. Output ONLY the core entity, name, or word.\n"
            "Output the concise answer inside <ans> and </ans> tags. "
            "Do not output any reasoning or other text."
        )
    raise ValueError(f"Unknown task: {task}")
 
 
def build_gender_cot_prompt(task, target_gender):
    """CoT variants, mirroring the env-sound CoT prompt structure: numbered
    steps, then the tag contract with the explicit 'no reasoning inside the
    tag' clause (resolves the instruction-contradiction issue found in the
    original CoT prompt)."""
    noun = GENDER_NOUN[target_gender]
    if task == "math":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "math problems played sequentially, one spoken by a male voice and "
            "one spoken by a female voice.\n"
            "Think through this step by step:\n"
            f"1. Identify which segment is spoken by the {noun}.\n"
            "2. State the math problem spoken in that segment.\n"
            "3. Compute the answer to that math problem.\n"
            "After your reasoning, output ONLY the final number inside <ans> "
            "and </ans> tags.\n"
            "The <ans> tag must contain only the final numeric answer -- no "
            "reasoning inside the tag itself."
        )
    if task == "trivia":
        return (
            "Listen to the audio carefully. It contains exactly TWO distinct "
            "trivia questions played sequentially, one spoken by a male voice "
            "and one spoken by a female voice.\n"
            "Think through this step by step:\n"
            f"1. Identify which segment is spoken by the {noun}.\n"
            "2. State the trivia question spoken in that segment.\n"
            "3. Answer that trivia question.\n"
            "After your reasoning, output ONLY the shortest possible answer "
            "(the core entity, name, or word) inside <ans> and </ans> tags.\n"
            "The <ans> tag must contain only the concise final answer -- no "
            "reasoning inside the tag itself."
        )
    raise ValueError(f"Unknown task: {task}")
 
 
def _pre_tag_text_len(raw):
    """Length of text preceding the first <ans> tag -- a cheap indicator of
    whether the model produced visible reasoning under CoT (cf. the finding
    that most models skip straight to the tag)."""
    idx = raw.lower().find("<ans>")
    return len(raw[:idx].strip()) if idx >= 0 else len(raw.strip())
 
 
def _grade(task, prediction_raw, expected_answers):
    """Returns (prediction_clean, is_correct). Mirrors the per-task grading
    conventions of the env-sound baselines."""
    if task == "math":
        prediction_clean = extract_math_answer(prediction_raw)
        is_correct = any(prediction_clean == str(a) for a in expected_answers)
    else:  # trivia
        extracted = extract_trivia_answer(prediction_raw)
        prediction_clean = normalize_answer(extracted)
        gt_norm = [normalize_answer(str(a)) for a in expected_answers]
        is_correct = prediction_clean in gt_norm if prediction_clean else False
    return prediction_clean, is_correct
 
 
def _matches_answers(task, prediction_clean, expected_answers):
    if not prediction_clean:
        return False
    if task == "math":
        return any(prediction_clean == str(a) for a in expected_answers)
    return prediction_clean in [normalize_answer(str(a)) for a in expected_answers]
 
 
def evaluate_conditional_gender(model, dataset_dir, metadata_path, output_path,
                                task="math", use_cot=False):
    assert task in ("math", "trivia")
    style = "CoT" if use_cot else "baseline"
    print(f"\n--- Starting Gender-Conditioned Compositional Evaluation "
          f"({task}, {style}) ---")
 
    with open(metadata_path, "r", encoding="utf-8") as f:
        records = [json.loads(line.strip()) for line in f]
 
    # ==========================================
    # Checkpoint and resume logic
    # ==========================================
    processed_ids = set()
    correct_count = 0
    total_tested = 0
    # accuracy conditioned on target position and target gender
    cond = {("pos", 0): [0, 0], ("pos", 1): [0, 0],
            ("gen", "male"): [0, 0], ("gen", "female"): [0, 0]}
 
    def _tally(data):
        nonlocal correct_count, total_tested
        total_tested += 1
        ok = bool(data.get("is_correct"))
        if ok:
            correct_count += 1
        p = data.get("target_index")
        g = data.get("target_gender")
        if ("pos", p) in cond:
            cond[("pos", p)][0] += ok
            cond[("pos", p)][1] += 1
        if ("gen", g) in cond:
            cond[("gen", g)][0] += ok
            cond[("gen", g)][1] += 1
 
    if os.path.exists(output_path):
        with open(output_path, "r", encoding="utf-8") as f:
            for line in f:
                try:
                    data = json.loads(line.strip())
                    processed_ids.add(data["concat_id"])
                    _tally(data)
                except json.JSONDecodeError:
                    continue
 
    if processed_ids:
        print(f"Detected historical progress! {len(processed_ids)} tests completed.")
        print(
            f"Current historical accuracy: "
            f"{correct_count / total_tested:.2%} ({correct_count}/{total_tested})"
        )
        print("Automatically skipping completed items...\n")
    # ==========================================
 
    for record in tqdm(records, desc=f"Gender-Conditioned {task}"):
        concat_id = record["concat_id"]
        if concat_id in processed_ids:
            continue
 
        audio_path = os.path.join(dataset_dir, record["audio_path"])
 
        # Prefer the pre-assigned balanced target from the dataset metadata
        # (position x gender fully crossed at generation time). Fall back to
        # the seeded-random convention for older metadata without the field.
        if "target_index" in record:
            target_index = record["target_index"]
            target_segment = record["sequence"][target_index]
        else:
            rng = random.Random(concat_id)
            target_segment = rng.choice(record["sequence"])
            target_index = record["sequence"].index(target_segment)
        target_gender = target_segment["gender"]
        expected_answers = get_expected_answers(target_segment)
        distractors = [seg for seg in record["sequence"] if seg != target_segment]
 
        if use_cot:
            prompt = build_gender_cot_prompt(task, target_gender)
        else:
            prompt = build_gender_prompt(task, target_gender)
 
        prediction_raw = model.query(audio_path, prompt).strip()
        prediction_clean, is_correct = _grade(task, prediction_raw, expected_answers)
 
        # Distractor match
        is_distracted = False
        matched_distractor_gender = None
        if not is_correct:
            for dist in distractors:
                if _matches_answers(task, prediction_clean,
                                    get_expected_answers(dist)):
                    is_distracted = True
                    matched_distractor_gender = dist["gender"]
                    break
 
        if is_correct:
            error_type = "Correct"
        elif is_distracted:
            error_type = "Distracted"
        else:
            error_type = "Hallucination"
 
        result_dict = {
            "concat_id": concat_id,
            "task": task,
            "cue_type": "gender",
            "prompt_style": "cot" if use_cot else "baseline",
            # visible-reasoning indicator (chars before the first <ans> tag);
            # only meaningful under CoT, recorded always for symmetry
            "pre_tag_text_len": _pre_tag_text_len(prediction_raw),
            "target_gender": target_gender,
            "target_index": target_index,
            "target_question": target_segment["question"],
            "ground_truth": expected_answers,
            "prediction_raw": prediction_raw,
            "prediction_clean": prediction_clean,
            "is_correct": is_correct,
            "error_type": error_type,
            "is_distracted": is_distracted,
            "matched_distractor_gender": matched_distractor_gender,
            "all_distractors_info": [
                {"gender": d["gender"],
                 "expected_answers": get_expected_answers(d)}
                for d in distractors
            ],
        }
 
        _tally(result_dict)
        processed_ids.add(concat_id)
 
        with open(output_path, "a", encoding="utf-8") as out_f:
            out_f.write(json.dumps(result_dict, ensure_ascii=False) + "\n")
 
        display_gt = expected_answers[0] if expected_answers else ""
        print(
            f"\n[Concat ID: {concat_id} | Target: {target_gender} @ pos "
            f"{target_index}] GT: {display_gt} | Pred: {prediction_clean} | "
            f"Correct: {is_correct} | {error_type}"
        )
 
    # ---------------- Summary ----------------
    if not total_tested:
        print("No items evaluated.")
        return
    print(f"\nOverall accuracy: {correct_count / total_tested:.2%} "
          f"({correct_count}/{total_tested})")
    for (kind, key), (ok, n) in cond.items():
        if n:
            label = f"target={'1st' if key == 0 else '2nd'} segment" \
                if kind == "pos" else f"target={key} voice"
            print(f"P(correct | {label}): {ok / n:.2%}  (n={n})")
 
 
# Thin per-task wrappers, matching the codebase convention of
# evaluate_conditional_env_math / evaluate_conditional_env_trivia.
# Single shared implementation above -> graders cannot drift apart.
 
def evaluate_conditional_gender_math(model, dataset_dir, metadata_path,
                                     output_path):
    return evaluate_conditional_gender(
        model, dataset_dir, metadata_path, output_path, task="math")
 
 
def evaluate_conditional_gender_trivia(model, dataset_dir, metadata_path,
                                       output_path):
    return evaluate_conditional_gender(
        model, dataset_dir, metadata_path, output_path, task="trivia")
 
 
def evaluate_conditional_gender_math_cot(model, dataset_dir, metadata_path,
                                         output_path):
    return evaluate_conditional_gender(
        model, dataset_dir, metadata_path, output_path, task="math",
        use_cot=True)
 
 
def evaluate_conditional_gender_trivia_cot(model, dataset_dir, metadata_path,
                                           output_path):
    return evaluate_conditional_gender(
        model, dataset_dir, metadata_path, output_path, task="trivia",
        use_cot=True)
 